function dedupePuzzlesFirstWins(items: WordPuzzle[]): WordPuzzle[] {
  const seen = new Set<string>();
  const out: WordPuzzle[] = [];
  for (const p of items) {
    const key = `${p.category}:${p.answer.join("")}`;
    if (seen.has(key)) continue;
    seen.add(key);
    out.push(p);
  }
  return out;
}

